def main() -> None:
    out_dir = Path(__file__).resolve().parent
    bitmap = bytearray(COLS * HEIGHT)
    colors = bytearray([0xE6] * (COLS * ROWS))  # Default: Light Blue ink (E) on Blue paper (6)

    def set_cell_color(col: int, row: int, ink: int, paper: int) -> None:
        colors[row * COLS + col] = ((ink & 0xF) << 4) | (paper & 0xF)

    def draw_text(col: int, row: int, text: str, ink: int, paper: int) -> None:
        for idx, ch in enumerate(text):
            c = col + idx
            if c >= COLS:
                break
            set_cell_color(c, row, ink, paper)
            glyph = FONT_8X8.get(ch.upper(), FONT_8X8[" "])
            for gy in range(8):
                bitmap[(row * 8 + gy) * COLS + c] = glyph[gy]

    def set_pixel(px: int, py: int, on: bool = True) -> None:
        if 0 <= px < WIDTH and 0 <= py < HEIGHT:
            byte_idx = py * COLS + (px >> 3)
            bit_mask = 0x80 >> (px & 7)
            if on:
                bitmap[byte_idx] |= bit_mask
            else:
                bitmap[byte_idx] &= ~bit_mask

    # Crisp 2-pixel frame around the 320x200 canvas
    for x in range(WIDTH):
        set_pixel(x, 0)
        set_pixel(x, 1)
        set_pixel(x, HEIGHT - 2)
        set_pixel(x, HEIGHT - 1)
    for y in range(HEIGHT):
        set_pixel(0, y)
        set_pixel(1, y)
        set_pixel(WIDTH - 2, y)
        set_pixel(WIDTH - 1, y)

    # Header banner
    draw_text(6, 2, "**** 6502 GATE BY GATE ****", 0xE, 0x6)
    draw_text(4, 4, "320X200 16-COLOR VRAM VIDEO CARD", 0x1, 0x6)
    draw_text(2, 6, "C64 16-COLOR PALETTE SWATCHES:", 0x7, 0x6)

    # 16 palette swatches across rows 8..10 (2 columns per swatch, cols 4..35)
    hex_digits = "0123456789ABCDEF"
    for idx in range(16):
        c0 = 4 + idx * 2
        label_ink = 0x0 if idx in (1, 3, 7, 13, 15) else 0x1
        draw_text(c0, 8, hex_digits[idx], label_ink, idx)
        set_cell_color(c0 + 1, 8, idx, idx)
        set_cell_color(c0, 9, idx, idx)
        set_cell_color(c0 + 1, 9, idx, idx)
        for dy in range(16):
            for dx in range(16):
                # Keep label glyph on left half of row 8; fill rest solid paper=idx
                if dy >= 8 or dx >= 8:
                    set_pixel(c0 * 8 + dx, 8 * 8 + dy, False)

    # Geometric raster motif + colour clash demo box (rows 12..21)
    draw_text(2, 12, "8X8 CELL ATTRIBUTE GRID DEMO:", 0x3, 0x6)
    for row in range(14, 22):
        for col in range(3, 37):
            if col < 20:
                # Smooth 2-colour checkerboard (cyan/purple, green/dark grey)
                ink = 0x5 if ((row + col) % 2 == 0) else 0x3
                paper = 0xB if (row % 2 == 0) else 0x6
                set_cell_color(col, row, ink, paper)
            else:
                # Deliberate attribute stripes demonstrating 2-colour-per-8x8-cell clash
                ink = 0x7 if (col % 2 == 0) else 0xA
                paper = 0x2 if (row % 2 == 0) else 0x0
                set_cell_color(col, row, ink, paper)

            for gy in range(8):
                for gx in range(8):
                    px = col * 8 + gx
                    py = row * 8 + gy
                    val = ((px ^ py) & 4) != 0 if col < 20 else (((px + py) & 3) == 0)
                    set_pixel(px, py, val)

    draw_text(4, 23, "HOLD S2 TO TOGGLE BORDER COLOR", 0xF, 0x6)

    (out_dir / "bitmap.mem").write_text(
        "\n".join(f"{b:02x}" for b in bitmap) + "\n", encoding="utf-8"
    )
    (out_dir / "color.mem").write_text(
        "\n".join(f"{c:02x}" for c in colors) + "\n", encoding="utf-8"
    )
    print(f"Generated {len(bitmap)} bitmap bytes and {len(colors)} color bytes.")


if __name__ == "__main__":
    main()
