#!/usr/bin/env python3
"""Generate 320x200 16-colour C64-style bitmap.mem and color.mem for Lesson 8."""

from __future__ import annotations

from pathlib import Path

WIDTH = 320
HEIGHT = 200
COLS = 40
ROWS = 25

# Minimal 8x8 bitmap font (row-major, MSB = left pixel)
